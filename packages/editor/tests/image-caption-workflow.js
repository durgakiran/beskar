async (page) => {
  const assert = (v, m) => { if (!v) throw new Error(m); };
  const edit = page.locator('[data-fixture="edit"]');
  const inline = edit.locator('.image-inline-wrapper');
  const preview = page.getByRole('dialog', { name: 'Image caption', exact: true });
  await inline.locator('img').hover();
  await preview.waitFor();
  assert(await preview.innerText() === 'Inline caption example', 'hover caption text');
  await preview.hover();
  await page.waitForTimeout(350);
  assert(await preview.isVisible(), 'can move pointer into caption');
  await page.mouse.move(10, 10);
  await preview.waitFor({ state: 'hidden' });
  assert(await inline.locator('.inline-image-caption-indicator').count() === 0, 'no separate caption icon');
  await inline.locator('.image-inline-inner').focus();
  await preview.waitFor();
  await page.keyboard.press('Escape');
  await preview.waitFor({ state: 'hidden' });
  await inline.locator('img').click();
  await inline.getByRole('button', { name: 'Edit image caption' }).click();
  const draft = page.getByRole('textbox', { name: 'Image caption text' });
  await draft.fill('Unsaved edit');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert(await page.evaluate(() => window.imageEditor.state.doc.child(1).child(1).attrs.caption) === 'Inline caption example', 'cancel keeps original');
  await inline.getByRole('button', { name: 'Edit image caption' }).click();
  await draft.fill('Updated caption\nSecond line');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert(await page.evaluate(() => window.imageEditor.state.doc.child(1).child(1).attrs.caption) === 'Updated caption\nSecond line', 'save persists');
  const html = await page.evaluate(() => window.imageEditor.getHTML());
  assert(html.includes('image-inline-caption-export') && html.includes('Updated caption'), 'HTML export caption');
  await inline.getByRole('button', { name: 'Convert to block image' }).click();
  assert(await edit.locator('.image-block-wrapper').count() === 3, 'inline becomes block');
  const converted = edit.locator('.image-block-wrapper').nth(1);
  assert(await converted.getByRole('textbox', { name: 'Image caption', exact: true }).inputValue() === 'Updated caption\nSecond line', 'conversion preserves caption');
  await converted.locator('img').click();
  await converted.getByRole('button', { name: 'More image actions' }).click();
  await page.getByRole('menuitem', { name: 'Inline', exact: true }).click();
  assert(await page.evaluate(() => { let caption; window.imageEditor.state.doc.descendants(n => { if (n.type.name === 'imageInline') caption = n.attrs.caption; }); return caption; }) === 'Updated caption\nSecond line', 'block to inline retains caption');
  const reader = page.locator('[data-fixture="view"]');
  const saved = await page.evaluate(() => JSON.stringify(window.imageReader.getJSON()));
  await reader.locator('.image-inline-inner').hover();
  await preview.waitFor();
  assert(await reader.getByRole('button', { name: 'Edit image caption' }).count() === 0, 'read-only has no caption editor');
  assert(saved === await page.evaluate(() => JSON.stringify(window.imageReader.getJSON())), 'read-only preview does not mutate');
  await page.mouse.move(10, 10);
  await preview.waitFor({ state: 'hidden' });
  console.log('PASS: hover, focus, no extra icon, Escape, save/cancel, conversions, export, read-only');
}
