// Playwright CLI run-code body against tests/images.html after building the editor.
async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const first = page.locator('[data-fixture="edit"] .image-block-wrapper').first();
  const img = first.locator('img');
  await img.click();
  const before = await img.boundingBox();
  const right = first.getByRole('button', { name: 'Resize image from right' });
  const handle = await right.boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2 + 40, handle.y + handle.height / 2, { steps: 5 });
  await page.mouse.up();
  const after = await img.boundingBox();
  assert(Math.abs(after.width - before.width - 80) <= 2, 'center width changes twice pointer delta');
  assert(Math.abs(after.x + after.width - before.x - before.width - 40) <= 2, 'edge tracks cursor');
  await right.press('Home');
  assert(Math.abs((await img.boundingBox()).width - 50) <= 1, '50px minimum');
  await right.press('Shift+ArrowRight');
  assert(Math.abs((await img.boundingBox()).width - 75) <= 1, 'keyboard larger step');
  await first.getByRole('button', { name: 'Align left', exact: true }).click();
  const leftBox = await img.boundingBox(), wrapper = await first.boundingBox();
  assert(Math.abs(leftBox.x - wrapper.x) < 2, 'left alignment');
  await first.getByRole('button', { name: 'Align right', exact: true }).click();
  const rightBox = await img.boundingBox();
  assert(Math.abs(rightBox.x + rightBox.width - wrapper.x - wrapper.width) < 2, 'right alignment');
  const leftHandle = first.getByRole('button', { name: 'Resize image from left' });
  await leftHandle.press('ArrowLeft');
  assert(Math.abs((await img.boundingBox()).width - 85) < 2, 'left handle keyboard direction');
  await first.getByRole('button', { name: 'More image actions' }).click();
  await page.getByRole('menuitem', { name: 'Duplicate', exact: true }).click();
  assert(await page.locator('[data-fixture="edit"] .image-block-wrapper').count() === 3, 'duplicate adds image');
  assert(await page.evaluate(() => window.imageEditor.state.doc.child(1).attrs.caption) === 'Preserve this caption', 'duplicate preserves caption');
  const cell = page.locator('[data-fixture="edit"] td .image-block-wrapper').first();
  await cell.locator('img').click();
  const availableBefore = (await cell.boundingBox()).width;
  await cell.getByRole('button', { name: 'Resize image from right' }).press('End');
  const cellImage = await cell.locator('img').boundingBox(), cellWrapper = await cell.boundingBox();
  assert(cellImage.width <= cellWrapper.width + 1 && Math.abs(cellImage.width - availableBefore) <= 1, 'nested image uses its own available width');
  const storedWidth = await page.evaluate(() => { let width; window.imageEditor.state.doc.descendants(n => { if(n.type.name === 'tableCell') width ??= n.child(0).attrs.width; }); return width; });
  assert(Math.abs(storedWidth - cellImage.width) <= 1, 'stored and rendered nested widths agree');
  const reader = page.locator('[data-fixture="view"]');
  const saved = await page.evaluate(() => JSON.stringify(window.imageReader.getJSON()));
  await reader.locator('.image-block-wrapper img').click();
  assert(await reader.locator('.image-resize-handle').count() === 0, 'read-only has no resize controls');
  assert(await reader.getByRole('button', { name: 'More image actions' }).count() === 0, 'read-only has no mutation menu');
  const download = page.waitForEvent('download');
  await reader.getByRole('button', { name: 'Download image' }).click();
  assert((await download).suggestedFilename() === 'image.svg', 'download original image');
  assert(saved === await page.evaluate(() => JSON.stringify(window.imageReader.getJSON())), 'reader document unchanged');
  console.log('PASS: drag tracking, minimum, keyboard, alignment, duplicate, nested bounds, reader download');
}
