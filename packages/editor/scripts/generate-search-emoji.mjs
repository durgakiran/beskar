// Run from packages/editor: node scripts/generate-search-emoji.mjs
import { gitHubEmojis } from '@tiptap/extension-emoji';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const names = new Set(gitHubEmojis.flatMap(item => [item.name, ...item.shortcodes]));
const entries = [...names].sort().map(name => {
  // Match Tiptap's first-match lookup, including aliases and image-only emoji.
  const item = gitHubEmojis.find(item => item.name === name || item.shortcodes.includes(name));
  return `\t${JSON.stringify(name)}: ${JSON.stringify(item.emoji || `:${name}:`)},`;
});
const source = `// Code generated by packages/editor/scripts/generate-search-emoji.mjs; DO NOT EDIT.

package searchtext

var emojiTextByName = map[string]string{
${entries.join('\n')}
}
`;
writeFileSync(new URL('../../../server/searchtext/emoji_generated.go', import.meta.url),
  execFileSync('gofmt', { input: source, encoding: 'utf8' }));
