package space

import (
	"context"
	"encoding/xml"
	"errors"
	"os"
	"reflect"
	"testing"
	"time"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// Opt-in: run only against a disposable database named page_order_test.
func TestPageFractionalOrderingPostgres(t *testing.T) {
	dsn := os.Getenv("PAGE_ORDER_TEST_DSN")
	if dsn == "" {
		t.Skip("set PAGE_ORDER_TEST_DSN to a disposable page_order_test database")
	}
	config, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	if config.ConnConfig.Database != "page_order_test" {
		t.Fatal("requires disposable page_order_test database")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	pool, err := pgxpool.NewWithConfig(ctx, config)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.Close()
	exec := func(sql string, args ...any) {
		t.Helper()
		if _, err := pool.Exec(ctx, sql, args...); err != nil {
			t.Fatal(err)
		}
	}
	exec(`DROP SCHEMA IF EXISTS core CASCADE; CREATE SCHEMA core;
        CREATE TABLE core.space(id uuid PRIMARY KEY, archived_at timestamptz, deleted_at timestamptz);
        CREATE TABLE core.page(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, space_id uuid NOT NULL REFERENCES core.space(id), parent_id bigint, sort_position bigint);
        CREATE INDEX page_sibling_order_idx ON core.page(space_id, (GREATEST(COALESCE(parent_id,0),0)), sort_position, id);`)
	space := uuid.New()
	otherSpace := uuid.New()
	exec(`INSERT INTO core.space(id) VALUES ($1),($2)`, space, otherSpace)
	exec(`INSERT INTO core.page(id,space_id,parent_id,sort_position) VALUES
        (1,$1,NULL,30),(2,$1,0,10),(3,$1,-1,20),(4,$1,0,NULL),
        (11,$1,1,1),(12,$1,1,2),(20,$2,0,1)`, space, otherSpace)
	migration, err := os.ReadFile("../../db/beskar/updates/page_fractional_ordering.xml")
	if err != nil {
		t.Fatal(err)
	}
	var changelog struct {
		Changes []struct {
			SQL      string `xml:"sql"`
			Rollback struct {
				SQL string `xml:"sql"`
			} `xml:"rollback"`
		} `xml:"changeSet"`
	}
	if err := xml.Unmarshal(migration, &changelog); err != nil {
		t.Fatal(err)
	}
	exec(changelog.Changes[0].SQL)
	exec(`SELECT setval(pg_get_serial_sequence('core.page','id'),100)`)

	ids := func(parent int64) []int64 {
		t.Helper()
		rows, err := pool.Query(ctx, `SELECT id FROM core.page WHERE space_id=$1 AND GREATEST(COALESCE(parent_id,0),0)=$2 ORDER BY sort_key`, space, parent)
		if err != nil {
			t.Fatal(err)
		}
		out, err := pgx.CollectRows(rows, pgx.RowTo[int64])
		if err != nil {
			t.Fatal(err)
		}
		return out
	}
	versions := func() map[int64]string {
		t.Helper()
		rows, err := pool.Query(ctx, `SELECT id,xmin::text FROM core.page`)
		if err != nil {
			t.Fatal(err)
		}
		defer rows.Close()
		result := map[int64]string{}
		for rows.Next() {
			var id int64
			var version string
			if err := rows.Scan(&id, &version); err != nil {
				t.Fatal(err)
			}
			result[id] = version
		}
		if err := rows.Err(); err != nil {
			t.Fatal(err)
		}
		return result
	}
	onlyChanged := func(before map[int64]string, source int64) {
		t.Helper()
		after := versions()
		for id, version := range before {
			if (after[id] != version) != (id == source) {
				t.Fatalf("unexpected row update id=%d source=%d", id, source)
			}
		}
	}
	reorder := func(source, target int64, placement string) error {
		return pageChangeTransaction(ctx, pool.BeginTx, func(tx pgx.Tx) error {
			return reorderPageInTransaction(ctx, tx, space, source, ReorderPageRequest{TargetPageId: target, Placement: placement})
		})
	}
	move := func(source int64, parent *int64) error {
		return pageChangeTransaction(ctx, pool.BeginTx, func(tx pgx.Tx) error {
			return movePageInTransaction(ctx, tx, space, source, MovePageRequest{ParentId: parent})
		})
	}

	t.Run("preserves saved order and root sentinels", func(t *testing.T) {
		if got := ids(0); !reflect.DeepEqual(got, []int64{2, 3, 1, 4}) {
			t.Fatalf("backfill order %v", got)
		}
	})
	t.Run("one reorder updates only its page", func(t *testing.T) {
		before := versions()
		if err := reorder(4, 2, "before"); err != nil {
			t.Fatal(err)
		}
		onlyChanged(before, 4)
		if got := ids(0); !reflect.DeepEqual(got, []int64{4, 2, 3, 1}) {
			t.Fatalf("saved order %v", got)
		}
		before = versions()
		if err := reorder(4, 2, "before"); err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(before, versions()) {
			t.Fatal("no-op reorder updated a row")
		}
	})
	t.Run("does not conflict with a shared space row lock", func(t *testing.T) {
		lock, err := pool.Begin(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer lock.Rollback(ctx)
		if _, err := lock.Exec(ctx, `SELECT id FROM core.space WHERE id=$1 FOR SHARE`, space); err != nil {
			t.Fatal(err)
		}
		if err := reorder(1, 4, "before"); err != nil {
			t.Fatalf("reorder waited on space: %v", err)
		}
	})
	t.Run("rejects different parents and spaces", func(t *testing.T) {
		if !errors.Is(reorder(11, 2, "before"), errPageOrderSiblings) {
			t.Fatal("cross-parent reorder accepted")
		}
		if !errors.Is(reorder(1, 20, "before"), errMovePageNotFound) {
			t.Fatal("cross-space reorder accepted")
		}
	})
	t.Run("move appends with one row update and cannot create a cycle", func(t *testing.T) {
		before := versions()
		parent := int64(1)
		if err := move(2, &parent); err != nil {
			t.Fatal(err)
		}
		onlyChanged(before, 2)
		if got := ids(1); !reflect.DeepEqual(got, []int64{11, 12, 2}) {
			t.Fatalf("move order %v", got)
		}
		if !errors.Is(move(1, &parent), errMovePageCycle) {
			t.Fatal("self move accepted")
		}
		descendant := int64(11)
		if !errors.Is(move(1, &descendant), errMovePageCycle) {
			t.Fatal("cycle accepted")
		}
		before = versions()
		if err := move(2, &parent); err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(before, versions()) {
			t.Fatal("same-parent move updated a row")
		}
	})
	t.Run("cross-parent sibling placement is atomic and changes one row", func(t *testing.T) {
		parent := int64(1)
		anchor := int64(12)
		place := func(source int64, request MovePageRequest) error {
			return pageChangeTransaction(ctx, pool.BeginTx, func(tx pgx.Tx) error {
				return movePageInTransaction(ctx, tx, space, source, request)
			})
		}
		before := versions()
		if err := place(3, MovePageRequest{ParentId: &parent, TargetPageId: &anchor, Placement: "before"}); err != nil {
			t.Fatal(err)
		}
		onlyChanged(before, 3)
		if got := ids(1); !reflect.DeepEqual(got, []int64{11, 3, 12, 2}) {
			t.Fatalf("cross-parent placement %v", got)
		}
		before = versions()
		if err := place(3, MovePageRequest{ParentId: &parent, TargetPageId: &anchor, Placement: "after"}); err != nil {
			t.Fatal(err)
		}
		onlyChanged(before, 3)
		if got := ids(1); !reflect.DeepEqual(got, []int64{11, 12, 3, 2}) {
			t.Fatalf("same-parent placement %v", got)
		}
		before = versions()
		if !errors.Is(place(3, MovePageRequest{TargetPageId: &anchor, Placement: "before"}), errPageOrderSiblings) {
			t.Fatal("stale anchor parent accepted")
		}
		if !reflect.DeepEqual(before, versions()) {
			t.Fatal("failed anchored move changed a row")
		}
		rootAnchor := int64(4)
		if err := place(3, MovePageRequest{TargetPageId: &rootAnchor, Placement: "after"}); err != nil {
			t.Fatal(err)
		}
		if got := ids(0); !reflect.DeepEqual(got, []int64{1, 4, 3}) {
			t.Fatalf("root promotion order %v", got)
		}
	})
	t.Run("new creators append and ranks stay short", func(t *testing.T) {
		before := ids(0)
		for range 200 {
			exec(`INSERT INTO core.page(space_id,parent_id) VALUES ($1,-1)`, space)
		}
		after := ids(0)
		if !reflect.DeepEqual(before, after[:len(before)]) {
			t.Fatal("new pages did not append")
		}
		var maxLength int
		if err := pool.QueryRow(ctx, `SELECT max(length(sort_key)) FROM core.page`).Scan(&maxLength); err != nil || maxLength > 12 {
			t.Fatalf("append rank length=%d err=%v", maxLength, err)
		}
	})
	t.Run("concurrent page creators get distinct append ranks", func(t *testing.T) {
		tx1, err := pool.Begin(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer tx1.Rollback(ctx)
		tx2, err := pool.Begin(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer tx2.Rollback(ctx)
		var key1, key2 string
		if err := tx1.QueryRow(ctx, `INSERT INTO core.page(space_id,parent_id) VALUES ($1,0) RETURNING sort_key`, space).Scan(&key1); err != nil {
			t.Fatal(err)
		}
		if err := tx2.QueryRow(ctx, `INSERT INTO core.page(space_id,parent_id) VALUES ($1,0) RETURNING sort_key`, space).Scan(&key2); err != nil {
			t.Fatal(err)
		}
		if key1 >= key2 {
			t.Fatalf("concurrent creation order: %q >= %q", key1, key2)
		}
		if _, err := pageSortKeyBetween(key1, key2); err != nil {
			t.Fatalf("creator generated incompatible ranks: %v", err)
		}
		if err := tx1.Commit(ctx); err != nil {
			t.Fatal(err)
		}
		if err := tx2.Commit(ctx); err != nil {
			t.Fatal(err)
		}
	})
	t.Run("page row contention returns a bounded conflict", func(t *testing.T) {
		lock, err := pool.Begin(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer lock.Rollback(ctx)
		if _, err := lock.Exec(ctx, `SELECT id FROM core.page WHERE id=3 FOR SHARE`); err != nil {
			t.Fatal(err)
		}
		before := versions()
		if !errors.Is(reorder(3, 1, "before"), errPageChangeConflict) {
			t.Fatal("expected row contention conflict")
		}
		if !reflect.DeepEqual(before, versions()) {
			t.Fatal("failed request updated pages")
		}
	})
	t.Run("concurrent gap inserts conflict", func(t *testing.T) {
		tx1, err := pool.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.Serializable})
		if err != nil {
			t.Fatal(err)
		}
		defer tx1.Rollback(ctx)
		tx2, err := pool.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.Serializable})
		if err != nil {
			t.Fatal(err)
		}
		defer tx2.Rollback(ctx)
		// Capture tx2's snapshot before tx1 changes the gap.
		if _, err := getPageOrderState(ctx, tx2, space, 3); err != nil {
			t.Fatal(err)
		}
		req := ReorderPageRequest{TargetPageId: 11, Placement: "before"}
		if err := reorderPageInTransaction(ctx, tx1, space, 2, req); err != nil {
			t.Fatal(err)
		}
		if err := tx1.Commit(ctx); err != nil {
			t.Fatal(err)
		}
		err = reorderPageInTransaction(ctx, tx2, space, 12, req)
		if err == nil {
			err = tx2.Commit(ctx)
		}
		if !errors.Is(pageChangeError(err), errPageChangeConflict) {
			t.Fatalf("expected 409 conflict, got %v", err)
		}
	})
	t.Run("concurrent opposite moves cannot commit a cycle", func(t *testing.T) {
		exec(`INSERT INTO core.page(id,space_id,parent_id) VALUES (1001,$1,0),(1002,$1,0)`, space)
		tx1, err := pool.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.Serializable})
		if err != nil {
			t.Fatal(err)
		}
		defer tx1.Rollback(ctx)
		tx2, err := pool.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.Serializable})
		if err != nil {
			t.Fatal(err)
		}
		defer tx2.Rollback(ctx)
		if _, err := getPageOrderState(ctx, tx2, space, 1002); err != nil {
			t.Fatal(err)
		}
		a, b := int64(1001), int64(1002)
		if err := movePageInTransaction(ctx, tx1, space, a, MovePageRequest{ParentId: &b}); err != nil {
			t.Fatal(err)
		}
		if err := tx1.Commit(ctx); err != nil {
			t.Fatal(err)
		}
		err = movePageInTransaction(ctx, tx2, space, b, MovePageRequest{ParentId: &a})
		if err == nil {
			err = tx2.Commit(ctx)
		}
		if !errors.Is(pageChangeError(err), errPageChangeConflict) {
			t.Fatalf("expected cycle conflict, got %v", err)
		}
	})
	t.Run("archived spaces reject changes", func(t *testing.T) {
		exec(`UPDATE core.space SET archived_at=now() WHERE id=$1`, space)
		if !errors.Is(reorder(1, 3, "before"), errMoveSpaceReadOnly) {
			t.Fatal("archived space changed")
		}
		exec(`UPDATE core.space SET archived_at=NULL WHERE id=$1`, space)
	})
	t.Run("rollback preserves current order", func(t *testing.T) {
		before := ids(0)
		exec(changelog.Changes[0].Rollback.SQL)
		rows, err := pool.Query(ctx, `SELECT id FROM core.page WHERE space_id=$1 AND GREATEST(COALESCE(parent_id,0),0)=0 ORDER BY sort_position,id`, space)
		if err != nil {
			t.Fatal(err)
		}
		after, err := pgx.CollectRows(rows, pgx.RowTo[int64])
		if err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(before, after) {
			t.Fatal("rollback lost order")
		}
	})
}
